#!/usr/bin/env python3
"""Generate ordered-dither materials without duplicating Mario's geometry."""
import argparse
from pathlib import Path
import re

from generate_mario_silhouette import ARRAY, BASE, ROOT, palette_source

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source


def variant_source(text, variant):
    active = True
    result = []
    for line in text.splitlines():
        if line == '#if MARIO_PALETTE_VARIANT':
            active = bool(variant)
        elif line == '#else':
            active = not active
        elif line == '#endif':
            active = True
        elif active:
            result.append(line)
    return '\n'.join(result)


def outputs():
    sources = [read_source(BASE / name) for name in ('model.inc.c', 'he_thicc_body.inc.c')]
    materials = read_source(BASE / 'palette_materials.inc.c')
    layouts = [read_source(BASE / 'geo.inc.c')]
    for variant, palette, body in ((0, '', ''), (1, 'he_thicc_', 'he_thicc_body_')):
        colours = dict(re.findall(r'^#define (MARIO_PALETTE_\w+) (\w+)$',
                                  variant_source(read_source(BASE / 'palette.h'), variant), re.M))
        text = variant_source(palette_source(materials, palette, body), variant)
        for name, value in colours.items():
            text = re.sub(r'\b' + name + r'\b', value, text)
        sources.append(text)
        layouts.append(palette_source(read_source(BASE / 'palette_geo.inc.c'), palette, body))
    blocks = {m[1]: m[2] for source in sources for m in ARRAY.finditer(source)}
    roots = sorted(set(name for layout in layouts for name in re.findall(
        r'GEO_(?:DISPLAY_LIST|ANIMATED_PART)\([^\n]*,\s*(\w+)\)', layout) if name in blocks))
    gbi = read_source(ROOT / 'include/n64/PR/gbi.h')
    modes = dict(re.findall(r'^#define\s+(G_CC_\w+)\s+([^\n]+)', gbi, re.M))

    def combiner(name):
        value = modes[name].strip()
        while value in modes:
            value = modes[value].strip()
        terms = [term.strip() for term in value.split(',')]
        if len(terms) != 8:
            raise ValueError(f'Unreviewed Mario combiner: {name}')
        return terms

    changed = {}

    def convert(name):
        if name in changed:
            return changed[name]
        text = blocks[name]
        children = re.findall(r'gsSP(?:DisplayList|BranchList)\((\w+)\)', text)
        for child in children:
            if child in blocks and convert(child):
                text = re.sub(r'\b' + child + r'\b', 'mario_dither_' + child, text)

        def replace(match):
            first, second = combiner(match[1]), combiner(match[2])
            # Cycle one decides the shared screen-space cutout; cycle two
            # retains the original colour, blend alpha and texture masks.
            first[4:] = (['TEXEL0', '0', 'PRIMITIVE', '0']
                         if 'TEXEL0' in first[4:] else ['0', '0', '0', 'PRIMITIVE'])
            second = [term.replace('TEXEL0', 'TEXEL1') for term in second]
            return 'gsDPSetCombineLERP(' + ', '.join(first + second) + ')'

        text = re.sub(r'gsDPSetCombineMode\((G_CC_\w+),\s*(G_CC_\w+)\)', replace, text)
        changed[name] = text if text != blocks[name] else None
        return changed[name]

    for name in roots:
        convert(name)
    names = sorted(name for name, text in changed.items() if text)
    banner = '// Generated by tools/generate_mario_dither.py. Do not edit by hand.\n'
    assets = [banner, '// clang-format off\n']
    assets.extend(f'static const Gfx mario_dither_{name}[];\n' for name in names)
    assets.extend(f'static const Gfx mario_dither_{name}[] = {{{changed[name]}\n}};\n'
                  for name in names)
    header = [banner, '#ifndef MARIO_DITHER_H\n#define MARIO_DITHER_H\n']
    lookup = [banner, '// clang-format off\n',
              'static const struct MarioDitherMap sMarioDitherMap[] = {\n']
    for name in roots:
        # Limbs often inherit the preceding body's combiner. They still need
        # the same two-cycle threshold, even when they contain only geometry.
        draw = 'mario_dither_' + name if changed[name] else name
        for suffix, compare in (('', 'G_AC_THRESHOLD'), ('noise_', 'G_AC_DITHER')):
            wrapper = 'mario_dither_draw_' + suffix + name
            assets.append(f'const Gfx {wrapper}[] = {{\n'
                      '    gsDPPipeSync(),\n'
                      '    gsDPSetCycleType(G_CYC_2CYCLE),\n'
                      # Both passes must accept the same coverage sample, too.
                      # AA accepts edge pixels that the ordinary cutout rejects.
                      '    gsSPSetOtherMode(G_SETOTHERMODE_L, 3, 1, 0),\n'
                      # Change only cycle one's blender muxes. Cycle two keeps
                      # the layer's ordinary or silhouette blend and depth mode.
                      '    gsSPSetOtherMode(G_SETOTHERMODE_L, 30, 2, (G_RM_PASS) & 0xC0000000),\n'
                      '    gsSPSetOtherMode(G_SETOTHERMODE_L, 26, 2, (G_RM_PASS) & 0x0C000000),\n'
                      '    gsSPSetOtherMode(G_SETOTHERMODE_L, 22, 2, (G_RM_PASS) & 0x00C00000),\n'
                      '    gsSPSetOtherMode(G_SETOTHERMODE_L, 18, 2, (G_RM_PASS) & 0x000C0000),\n'
                      '    gsDPSetColorDither(G_CD_MAGICSQ),\n'
                      '    gsDPSetAlphaDither(G_AD_PATTERN),\n'
                      '    gsDPSetBlendColor(0, 0, 0, 8),\n'
                      f'    gsDPSetAlphaCompare({compare}),\n'
                      f'    gsSPDisplayList({draw}),\n'
                      '    gsDPPipeSync(),\n'
                      '    gsDPSetAlphaCompare(G_AC_NONE),\n'
                      '    gsDPSetBlendColor(0, 0, 0, 0),\n'
                      '    gsDPSetCycleType(G_CYC_1CYCLE),\n'
                      '    gsSPEndDisplayList(),\n};\n')
            header.append(f'extern const Gfx {wrapper}[];\n')
        lookup.append(f'    {{ {name}, mario_dither_draw_{name}, '
                      f'mario_dither_draw_noise_{name} }},\n')
    assets.append('// clang-format on\n')
    header.append('#endif\n')
    lookup.append('};\n// clang-format on\n')
    return {BASE / 'dither.inc.c': ''.join(assets), BASE / 'dither.h': ''.join(header),
            BASE / 'dither_map.inc.c': ''.join(lookup)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or read_source(path) != text:
                raise SystemExit(f'Stale Mario dither asset: {path}')
        else:
            path.write_text(text)
    print('Mario ordered-dither materials are current.')


if __name__ == '__main__':
    main()
