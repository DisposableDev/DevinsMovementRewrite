#!/usr/bin/env python3
"""Keep the encounter's Toad assets local to JRB and the game-over segment."""
from pathlib import Path
import argparse
import re
import subprocess

from check_quality import SetupError, clang_tool, load_config

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
BANNER = "// Generated by tools/generate_simpleflips_assets.py from vanilla actor data.\n"


def renamed(source, prefix):
    return re.sub(r"\btoad_seg6_", prefix, source)


def interactive_head(head):
    head = renamed(head, "intro_simpleflips_toad_")
    lists = dict(re.findall(r"const Gfx (\w+)\[\] = \{(.*?)\n\};", head, re.S))

    def flattened(name):
        commands = []
        for line in lists[name].splitlines():
            child = re.fullmatch(r"\s*gsSPDisplayList\((\w+)\),", line)
            if child:
                commands.extend(flattened(child[1]))
            elif line.strip() and "gsSPEndDisplayList()" not in line:
                commands.append(line)
        return commands

    commands = ["    gsDPPipeSync(),", "    gsDPSetEnvColor(255, 255, 255, 255),"]
    commands.extend(flattened("intro_simpleflips_toad_dl_06007710"))
    commands.append("    gsSPEndDisplayList(),")
    # Keep groups in vertex-load order. Runtime copies patch G_VTX commands, so
    # indices remain correct for microcodes whose macros expand differently.
    groups = re.findall(r"gsSPVertex\((\w+),\s*(\d+),\s*0\)", "\n".join(commands))
    head = head[:head.index("// 0x06007300 - 0x06007498")]
    head += "\nconst Gfx intro_simpleflips_head_dl[] = {\n" + "\n".join(commands) + "\n};\n"
    head += "\nstatic const struct SimpleFlipsHeadVertexGroup intro_simpleflips_head_groups[] = {\n"
    head += "".join(f"    {{ {name}, {count} }},\n" for name, count in groups)
    head += "};\n\nconst struct SimpleFlipsHeadMesh intro_simpleflips_head_mesh = {\n"
    head += ("    intro_simpleflips_head_dl, intro_simpleflips_head_groups,\n"
             "    ARRAY_COUNT(intro_simpleflips_head_dl), ARRAY_COUNT(intro_simpleflips_head_groups),\n"
             f"    {sum(int(count) for _, count in groups)},\n}};\n")
    # File-select hands live in its own segment 7, which is not loaded here.
    # Copy only these two textures and their small display lists into intro.
    menu = read_source(ROOT / "levels/menu/leveldata.c")
    hands = menu.split("// 0x070062E8 - 0x07006328")[1].split("// 0x070073D0")[0]
    for native, local in (("vertex_menu_hand", "intro_simpleflips_hand_vertices"),
                          ("texture_menu_idle_hand", "intro_simpleflips_idle_hand_texture"),
                          ("texture_menu_grabbing_hand", "intro_simpleflips_grabbing_hand_texture"),
                          ("dl_menu_idle_hand", "intro_simpleflips_idle_hand_dl"),
                          ("dl_menu_grabbing_hand", "intro_simpleflips_grabbing_hand_dl"),
                          ("dl_menu_hand", "intro_simpleflips_hand_dl")):
        hands = re.sub(rf"\b{native}\b", local, hands)
    return head + hands


def outputs():
    model = read_source(ROOT / "actors/toad/model.inc.c")
    # The opaque head is self-contained up to the transparent-head variant.
    head = model.split("// 0x06007788 - 0x06007808")[0]
    native_geo = read_source(ROOT / "actors/toad/geo.inc.c")
    native_geo = native_geo.split("// 0x0D00027C")[0]
    native_geo = native_geo.replace("toad_geo_000114", "jrb_simpleflips_toad_body")
    native_geo = native_geo.replace("LAYER_OCCLUDE_SILHOUETTE_OPAQUE", "LAYER_OPAQUE")
    native_geo = renamed(native_geo, "jrb_simpleflips_toad_")
    native_geo += """
const GeoLayout jrb_simpleflips_toad_geo[] = {
    GEO_NODE_START(),
    GEO_OPEN_NODE(),
        GEO_SCALE(0, 16384),
        GEO_OPEN_NODE(),
            GEO_BRANCH(1, jrb_simpleflips_toad_body),
        GEO_CLOSE_NODE(),
    GEO_CLOSE_NODE(),
    GEO_END(),
};
"""
    wave = read_source(ROOT / "actors/toad/anims/anim_06008F7C.inc.c")
    wave = renamed(wave, "jrb_simpleflips_toad_")
    punch = read_source(ROOT / "assets/anims/anim_67.inc.c")
    # Mario's DMA source declares its header first; normal actor data needs
    # the indices and values declared before that header's pointer initializer.
    animation = re.search(r"static const struct Animation anim_67\[\] = \{.*?\};", punch, re.S)[0]
    punch = punch.replace(animation, "") + "\n" + animation.replace("anim_67[]", "anim_67")
    punch = punch.replace("anim_67", "jrb_simpleflips_punch")
    animations = wave + "\n" + punch + """
const struct Animation *const jrb_simpleflips_anims[] = {
    &jrb_simpleflips_toad_anim_06008F7C,
    &jrb_simpleflips_punch,
};
"""
    mips_model = read_source(ROOT / "actors/mips/model.inc.c").replace("mips_seg6_", "jrb_simpleflips_mips_")
    mips_geo = read_source(ROOT / "actors/mips/geo.inc.c").replace("mips_seg6_", "jrb_simpleflips_mips_").replace("mips_geo", "jrb_simpleflips_mips_geo")
    mips_idle = read_source(ROOT / "actors/mips/anims/anim_06014B94.inc.c").replace("mips_seg6_", "jrb_simpleflips_mips_")
    mips_idle += "\nconst struct Animation *const jrb_simpleflips_mips_anims[] = { &jrb_simpleflips_mips_anim_06014B94 };\n"
    sign = read_source(ROOT / "actors/wooden_signpost/model.inc.c")
    # The later credit-sign list belongs to its native actor, not this copied bank.
    sign = sign.split("// Reuse the sign meshes and textures", 1)[0]
    sign = sign.replace("wooden_signpost_seg3_", "jrb_simpleflips_sign_")
    sign = sign.replace("G_CC_MODULATERGB,", "G_CC_MODULATERGBFADE,").replace("G_CC_MODULATERGB)", "G_CC_MODULATERGBFADE)")
    sign = sign.replace("G_CC_SHADE,", "G_CC_SHADEFADEA,").replace("G_CC_SHADE)", "G_CC_SHADEFADEA)")
    return {
        "levels/jrb/simpleflips/mips_model.inc.c": mips_model,
        "levels/jrb/simpleflips/mips_geo.inc.c": mips_geo,
        "levels/jrb/simpleflips/mips_anims.inc.c": mips_idle,
        "levels/jrb/simpleflips/sign_model.inc.c": sign,
        "levels/jrb/simpleflips/toad_model.inc.c": renamed(model, "jrb_simpleflips_toad_"),
        "levels/jrb/simpleflips/toad_geo.inc.c": native_geo,
        "levels/jrb/simpleflips/anims.inc.c": animations,
        "levels/intro/simpleflips_head.inc.c": interactive_head(head),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        formatter = clang_tool(ROOT, "clang-format", load_config(ROOT)["clang_version"])
    except SetupError as error:
        raise SystemExit(str(error)) from error
    for relative, content in outputs().items():
        path = ROOT / relative
        # Keep generation reproducible after the bank's existing source cleanup.
        content = subprocess.run(
            [formatter, "--style=file", "--assume-filename=" + str(path)],
            cwd=ROOT, input=BANNER + content, text=True, capture_output=True, check=True,
        ).stdout
        if args.check:
            if not path.exists() or read_source(path) != content:
                raise SystemExit(f"Outdated generated asset: {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
