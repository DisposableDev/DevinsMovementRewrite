#!/usr/bin/env python3
"""Add conservative RSP bounds to ordered, coarse JRB opaque terrain runs."""
import argparse
from itertools import product
from pathlib import Path
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "levels/jrb/areas/1/terrain_culling.inc.c"
ROOTS = ("07004940", "07004C78", "070058C8", "070069B0", "07007570")


# Only complete sections proven hidden through the padded tunnel opening.
TUNNEL_HIDDEN_SECTIONS = {
    "jrb_seg7_dl_070044C8_section_0_0",
    "jrb_seg7_dl_07004658_section_0_0",
    "jrb_seg7_dl_07004B88_section_0_0",
    "jrb_seg7_dl_07004BF0_section_0_0",
    "jrb_seg7_dl_070065A8_section_0_0",
    "jrb_seg7_dl_07006980_section_0_0",
}
CAVE_HIDDEN_SECTIONS = TUNNEL_HIDDEN_SECTIONS | {
    "jrb_seg7_dl_070041F0_section_1_0",
    "jrb_seg7_dl_07006508_section_0_0",
    "jrb_seg7_dl_070065A8_section_1_0",
    "jrb_seg7_dl_070065A8_section_1_1",
}


def bay_variants(text):
    """Share section geometry and preserve all parent material operations."""
    arrays = dict(re.findall(r"\bGfx\s+(\w+)\[\]\s*=\s*\{(.*?)\n\};", text, re.S))
    lines = []
    roots = {f"jrb_seg7_dl_{suffix}_culled" for suffix in ("07004940", "07004C78", "070069B0")}
    for variant, hidden in (("cave", CAVE_HIDDEN_SECTIONS), ("tunnel", TUNNEL_HIDDEN_SECTIONS)):
        assert hidden <= arrays.keys(), "terrain sections changed; re-audit portal masks"
        emitted = {}

        def clone(name):
            if re.fullmatch(r".*_section_\d+_\d+", name):
                return name
            if name in emitted:
                return emitted[name]
            replacement = name.removesuffix("_culled") + "_" + variant
            body = arrays[name]
            for child in re.findall(r"gsSPDisplayList\((\w+)\)", body):
                if child in hidden:
                    body = body.replace(f"    gsSPDisplayList({child}),\n", "")
                else:
                    body = body.replace(f"gsSPDisplayList({child})", f"gsSPDisplayList({clone(child)})")
            emitted[name] = replacement
            storage = "" if name in roots else "static "
            lines.append(f"{storage}const Gfx {replacement}[] = {{{body}\n}};\n")
            return replacement

        for root in sorted(roots):
            clone(root)
    return "\n".join(lines)


def pack_blocks(group, name, arrays, lines):
    """Batch adjacent geometry within the native 32-vertex cache, preserving order."""
    output = []
    vertices = []
    triangles = []
    batch = 0

    def flush():
        nonlocal batch
        if not vertices:
            return
        vertex_name = f"{name}_vertices_{batch}"
        lines.append(f"static const Vtx {vertex_name}[] = {{")
        lines.extend("    " + row for row in vertices)
        lines.append("};\n")
        output.append(f"    gsSPVertex({vertex_name}, {len(vertices)}, 0),\n")
        for offset in range(0, len(triangles), 2):
            pair = triangles[offset:offset + 2]
            fields = ", ".join(str(value) for triangle in pair for value in triangle)
            output.append(f"    gsSP{len(pair)}Triangle{'s' if len(pair) == 2 else ''}({fields}),\n")
        vertices.clear()
        triangles.clear()
        batch += 1

    for block, vertex, count in group:
        rows = [row.strip() for row in arrays[vertex][1].splitlines() if row.strip()][:count]
        assert len(rows) == count
        if len(vertices) + count > 32:
            flush()
        base = len(vertices)
        vertices.extend(rows)
        for operation, args in re.findall(r"(gsSP(?:1Triangle|2Triangles))\(([^)]+)\)", block):
            fields = [int(value.strip(), 0) for value in args.split(",")]
            for offset in range(0, len(fields), 4):
                triangles.append(tuple(base + value for value in fields[offset:offset + 3])
                                 + (fields[offset + 3],))
    flush()
    return "".join(output)


def generate():
    arrays = {}
    for part in range(2, 7):
        text = read_source(ROOT / f"levels/jrb/areas/1/{part}/model.inc.c")
        for kind, name, body in re.findall(
                r"\b(Vtx|Gfx)\s+(\w+)\[\]\s*=\s*\{(.*?)\n\};", text, re.S):
            arrays[name] = (kind, body)
    lines = ["// Generated by tools/generate_jrb_terrain.py; edit the generator.",
             "// Material setup/restoration remains outside the bounded geometry children."]
    sections = 0
    for suffix in ROOTS:
        root = "jrb_seg7_dl_" + suffix
        root_body = arrays[root][1]
        for child in re.findall(r"gsSPDisplayList\((\w+)\)", root_body):
            body = arrays[child][1]
            body = body.removesuffix("    gsSPEndDisplayList(),")
            block_pattern = r"    gsSPVertex[^\n]+\n(?:    gsSP(?:1Triangle|2Triangles)[^\n]+\n)+"
            runs = []
            cursor = 0
            for match in re.finditer(block_pattern, body):
                state = body[cursor:match.start()]
                if state.strip() or not runs:
                    runs.append((state, []))
                runs[-1][1].append(match.group())
                cursor = match.end()
            assert not body[cursor:].strip(), child
            caller = []
            for run_index, (state, blocks) in enumerate(runs):
                caller.extend(state.strip("\n").splitlines())
                groups = []
                current = []
                count = 0
                for block in blocks:
                    name, size = re.search(r"gsSPVertex\((\w+),\s*(\d+),\s*0\)", block).groups()
                    assert all(op in ("gsSPVertex", "gsSP1Triangle", "gsSP2Triangles")
                               for op in re.findall(r"\b(gs\w+)\(", block)), child
                    if current and count + int(size) > 48:
                        groups.append(current)
                        current = []
                        count = 0
                    current.append((block, name, int(size)))
                    count += int(size)
                groups.append(current)
                if len(groups) > 1 and sum(row[2] for row in groups[-1]) < 24:
                    groups[-2].extend(groups.pop())
                calls = []
                for index, group in enumerate(groups):
                    name = f"{child}_section_{run_index}_{index}"
                    points = []
                    for _, vertex, count in group:
                        points.extend(tuple(map(int, match)) for match in re.findall(
                            r"\{\{\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\}", arrays[vertex][1])[:count])
                    assert len(points) == sum(row[2] for row in group), name
                    bounded = len(points) >= 24
                    if bounded:
                        bounds = [(min(p[a] for p in points) - 1, max(p[a] for p in points) + 1)
                                  for a in range(3)]
                        lines.append(f"static const Vtx {name}_bounds[] = {{")
                        for x, y, z in product(*bounds):
                            lines.append(f"    {{{{{{{x}, {y}, {z}}}, 0, {{0, 0}}, {{0, 0, 0, 0}}}}}},")
                        lines.append("};\n")
                        sections += 1
                    packed = pack_blocks(group, name, arrays, lines)
                    lines.append(f"static const Gfx {name}[] = {{")
                    if bounded:
                        lines.extend(["    gsSPClearGeometryMode(G_LIGHTING),",
                                      f"    gsSPVertex({name}_bounds, 8, 0),",
                                      "    gsSPSetGeometryMode(G_LIGHTING),",
                                      "    gsSPCullDisplayList(0, 7),"])
                    lines.extend(packed.rstrip().splitlines())
                    lines.extend(["    gsSPEndDisplayList(),", "};\n"])
                    calls.append(f"    gsSPDisplayList({name}),")
                caller.extend(calls)
            lines.append(f"static const Gfx {child}_culled[] = {{")
            lines.extend(caller)
            lines.extend(["    gsSPEndDisplayList(),", "};\n"])
            root_body = root_body.replace(f"gsSPDisplayList({child})", f"gsSPDisplayList({child}_culled)")
        lines.append(f"const Gfx {root}_culled[] = {{")
        lines.extend(root_body.strip("\n").splitlines())
        lines.extend(["};", ""])
    text = "\n".join(lines)
    return text + bay_variants(text), sections


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, sections = generate()
    if args.check:
        if not OUT.exists() or read_source(OUT) != text:
            raise SystemExit("JRB terrain sections are stale; run tools/generate_jrb_terrain.py")
    else:
        OUT.write_text(text)
    print(f"JRB terrain: {sections} bounded sections; original material and triangle order retained")


if __name__ == "__main__":
    main()
