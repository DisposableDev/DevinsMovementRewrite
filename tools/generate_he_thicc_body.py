#!/usr/bin/env python3
"""Bake HE THICC body proportions; retain topology, UVs, bones and animation."""
import argparse
import math
from pathlib import Path
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'actors/mario'
BODY_PART = re.compile(r'butt|thigh|torso|pants_overalls|tshirt|yellow_button')
VERTEX = re.compile(r'\{\{\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\}(,\s*0,\s*\{[^}]+\},\s*)\{0x([\da-f]+),\s*0x([\da-f]+),\s*0x([\da-f]+),')


def collect_body_blocks(blocks):
    # Only the pelvis, torso (including buttons) and upper legs get new geometry.
    roots = {name for name in blocks if blocks[name][0] == 'Gfx' and BODY_PART.search(name)}
    selected = set()

    def visit(name):
        if name in selected:
            return
        selected.add(name)
        for dependency in re.findall(r'\b(?:gsSPDisplayList|gsSPVertex)\(\s*(\w+)', blocks[name][1]):
            if dependency in blocks:
                visit(dependency)

    for name in roots:
        visit(name)
    return roots, selected


def reshape(match, scale):
    xyz = [int(match[i]) for i in range(1, 4)]
    normal = [int(match[i], 16) for i in range(5, 8)]
    normal = [(n if n < 128 else n - 256) / s for n, s in zip(normal, scale)]
    length = math.sqrt(sum(n * n for n in normal))
    if length:
        normal = [round(n * 127 / length) for n in normal]
    xyz = [round(n * s) for n, s in zip(xyz, scale)]
    return '{{{%6d, %6d, %6d}%s{%s,' % (
        *xyz, match[4], ', '.join(f'0x{int(n) & 255:02x}' for n in normal))


def body_scale(name):
    if 'butt' in name:
        return (1.05, 1.25, 1.22)
    if 'thigh' in name:
        return (1.0, 1.22, 1.25)
    return (1.0, 1.22, 1.18)


def outputs():
    source = read_source(BASE / 'model.inc.c')
    blocks = {match[2]: (match[1], match[0]) for match in re.finditer(
        r'(?:static )?const (Vtx|Gfx) (\w+)\[\] = \{.*?\n\};', source, re.S)}
    roots, selected = collect_body_blocks(blocks)
    output = ['// Generated by tools/generate_he_thicc_body.py. Do not edit by hand.\n']

    # Original order preserves display-list dependency ordering.
    for name, (kind, block) in blocks.items():
        if name not in selected:
            continue
        if kind == 'Vtx':
            scale = body_scale(name)
            block = VERTEX.sub(lambda match: reshape(match, scale), block)
        block = re.sub(r'\b\w+\b', lambda match: 'he_thicc_body_' + match[0]
                       if match[0] in selected else match[0], block)
        output.append(block + '\n')

    declarations = '// Generated body display-list declarations.\n' + ''.join(
        f'extern const Gfx he_thicc_body_{name}[];\n' for name in sorted(roots))
    return {
        BASE / 'he_thicc_body.inc.c': '\n'.join(output),
        BASE / 'he_thicc_body.h': declarations,
    }, len(selected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify outputs without changing them')
    args = parser.parse_args()
    generated, count = outputs()
    for path, text in generated.items():
        if args.check:
            if not path.exists() or read_source(path) != text:
                raise SystemExit(f'Stale generated body: {path}')
        else:
            path.write_text(text)
    print(f'Generated {count} mesh/display-list blocks.')


if __name__ == '__main__':
    main()
