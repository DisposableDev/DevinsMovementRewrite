#!/usr/bin/env python3
"""Reuse Mario's exact visible geometry for opaque through-wall silhouettes."""
import argparse
from pathlib import Path
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'actors/mario'
ARRAY = re.compile(r'(?:static )?const Gfx (\w+)\[\] = \{(.*?)\n\};', re.S)
GEOMETRY = {'gsSPVertex', 'gsSP1Triangle', 'gsSP2Triangles', 'gsSPEndDisplayList'}


def palette_source(text, palette, body):
    text = re.sub(r'MARIO_PALETTE_NAME\((\w+)\)', lambda m: palette + m[1], text)
    return re.sub(r'MARIO_BODY_NAME\((\w+)\)', lambda m: body + m[1], text)


def collect_geometry():
    sources = [read_source(BASE / name) for name in ('model.inc.c', 'he_thicc_body.inc.c')]
    materials = read_source(BASE / 'palette_materials.inc.c')
    layout = read_source(BASE / 'palette_geo.inc.c')
    layouts = [read_source(BASE / 'geo.inc.c')]
    for palette, body in (('', ''), ('he_thicc_', 'he_thicc_body_')):
        sources.append(palette_source(materials, palette, body))
        layouts.append(palette_source(layout, palette, body))
    blocks = {m[1]: m[2] for text in sources for m in ARRAY.finditer(text)}
    roots = set()
    for text in layouts:
        roots.update(re.findall(r'GEO_(?:DISPLAY_LIST|ANIMATED_PART)\([^\n]*,\s*(\w+)\)', text))
    roots = sorted(name for name in roots if name in blocks and 'wing' not in name)
    pure = {name for name, text in blocks.items()
            if set(re.findall(r'\b(gs\w+)\(', text)) <= GEOMETRY}

    def leaves(name, parents=()):
        if name in parents:
            raise ValueError(f'Recursive Mario display list: {name}')
        text = blocks[name]
        if name in pure:
            return (name,)
        if ('wing' in name or re.search(r'gsSP(?:Clear|Set)GeometryMode\([^)]*(?:CULL|SMOOTH)', text)
                or re.search(r'gsSP(?:Vertex|1Triangle|2Triangles)\(', text)):
            raise ValueError(f'Review mixed geometry/material list: {name}')
        return tuple(leaf for child in re.findall(r'gsSP(?:DisplayList|BranchList)\((\w+)\)', text)
                     for leaf in leaves(child, parents + (name,)))

    mapping = {name: leaves(name) for name in roots}
    if any(not geometry for geometry in mapping.values()):
        raise ValueError('Empty Mario silhouette geometry')
    geometries = sorted(set(mapping.values()))
    if len(geometries) >= 64:
        raise ValueError('Mario silhouette geometry exceeds its six-bit node field')
    return blocks, mapping, geometries


def outputs():
    # Different meshes can protrude around visible Mario. Reuse the exact
    # ordinary geometry, including its selected detail level, in both passes.
    _, mapping, geometries = collect_geometry()
    indices = {geometry: i + 1 for i, geometry in enumerate(geometries)}
    banner = '// Generated by tools/generate_mario_silhouette.py. Do not edit by hand.\n'
    assets = [banner, '#include "config.h"\n\n#if SILHOUETTE\n',
              '// clang-format off\n']
    header = [banner, '#ifndef MARIO_SILHOUETTE_H\n#define MARIO_SILHOUETTE_H\n']
    for index, geometry in enumerate(geometries, 1):
        name = f'mario_silhouette_geometry_{index}'
        assets.append(f'const Gfx {name}[] = {{\n' + ''.join(
            f'    gsSPDisplayList({leaf}),\n' for leaf in geometry[:-1])
            + f'    gsSPBranchList({geometry[-1]}),\n}};\n')
        header.append(f'extern const Gfx {name}[];\n')
    assets.append('// clang-format on\n\n#endif\n')
    header.append('#endif // MARIO_SILHOUETTE_H\n')
    lookup = [banner, 'static const Gfx *const sMarioSilhouetteGeometry[] = {\n    NULL,\n']
    lookup.extend(f'    mario_silhouette_geometry_{index},\n' for index in range(1, len(geometries) + 1))
    lookup.append('};\n\nstatic const struct MarioSilhouetteMap sMarioSilhouetteMap[] = {\n')
    lookup.extend(f'    {{ {name}, {indices[mapping[name]]} }},\n'
                  for name in mapping)
    lookup.append('};\n')
    return {BASE / 'silhouette.inc.c': '\n'.join(assets),
            BASE / 'silhouette.h': ''.join(header),
            BASE / 'silhouette_map.inc.c': ''.join(lookup)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated assets without writing')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or read_source(path) != text:
                raise SystemExit(f'Stale Mario silhouette asset: {path}')
        else:
            path.write_text(text)
    print('Mario silhouette geometry and lookup are current.')


if __name__ == '__main__':
    main()
