#!/usr/bin/env python3
"""Generate one visible annulus for Bowser's matching damage annulus."""
import argparse
import math
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def output():
    lines = ["// Generated by tools/generate_bowser_wave.py.",
             "static const Vtx bowser_wave_ring_vertices[] = {"]
    for segment in range(4):
        for step in range(9):
            angle = (segment * 8 + step) * math.tau / 32
            for radius in (84, 100):
                x, z = round(math.sin(angle) * radius), round(math.cos(angle) * radius)
                lines.append(f"    {{ {{ {{ {x}, 0, {z} }}, 0, {{ 0, 0 }}, {{ 255, 255, 255, 255 }} }} }},")
    lines += ["};", "const Gfx bowser_wave_ring_dl[] = {", "    gsDPPipeSync(),",
              "    gsDPSetCombineMode(G_CC_SHADEFADEA, G_CC_SHADEFADEA),",
              "    gsSPClearGeometryMode(G_LIGHTING | G_CULL_BACK),"]
    for segment in range(4):
        lines.append(f"    gsSPVertex(bowser_wave_ring_vertices + {segment * 18}, 18, 0),")
        for step in range(8):
            a = step * 2
            lines.append(f"    gsSP2Triangles({a}, {a+1}, {a+3}, 0, {a}, {a+3}, {a+2}, 0),")
    lines += ["    gsDPPipeSync(),", "    gsDPSetCombineMode(G_CC_SHADE, G_CC_SHADE),",
              "    gsSPSetGeometryMode(G_LIGHTING | G_CULL_BACK),",
              "    gsDPSetEnvColor(255, 255, 255, 255),", "    gsSPEndDisplayList(),", "};"]
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "actors/impact_ring/bowser_wave_ring.inc.c"
    content = output()
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Stale Bowser wave geometry")
    else:
        path.write_text(content)
