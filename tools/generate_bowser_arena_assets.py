#!/usr/bin/env python3
"""Generate a private Fight 3 asset bank from unchanged native actor sources."""
import argparse
from pathlib import Path
from generate_physics_lab_enemies import DEFINITION, ROOT

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ACTORS = ("bully", "lakitu_enemy", "spiny_egg", "spiny", "mr_i_eyeball", "mr_i_iris", "boo", "snufit")
OUT = ROOT / "levels/bowser_3"

def outputs():
    definitions = {}
    assets, geos = [], []
    for actor in ACTORS:
        directory = ROOT / "actors" / actor
        for path in sorted(directory.rglob("*.inc.c")):
            for match in DEFINITION.finditer(read_source(path)):
                definitions[match["name"]] = match.groupdict()
        for name in ("model.inc.c", "anims/data.inc.c", "anims/table.inc.c"):
            path = directory / name
            if path.exists():
                assets.append(f'#include "{path.relative_to(ROOT)}"')
        geos.append(f'#include "actors/{actor}/geo.inc.c"')
    banner = "// Generated by tools/generate_bowser_arena_assets.py; edit the generator.\n"
    namespace = "\n".join(f"#define {name} bowser_arena_{name}" for name in sorted(definitions)) + "\n"
    cleanup = "\n".join(f"#undef {name}" for name in sorted(definitions)) + "\n"
    declarations = []
    for name, definition in sorted(definitions.items()):
        if "static" not in definition["qual"]:
            suffix = "[]" if definition["array"] else ""
            declarations.append(f"extern const {definition['type']} {definition['ptr']}bowser_arena_{name}{suffix};")
    return {
        "arena_enemy_namespace.inc.h": banner + namespace,
        "arena_enemy_assets.h": banner + '#ifndef BOWSER_ARENA_ENEMY_ASSETS_H\n#define BOWSER_ARENA_ENEMY_ASSETS_H\n#include "types.h"\n' + "\n".join(declarations) + "\n#endif\n",
        "arena_enemy_assets.inc.c": banner + '#include "levels/bowser_3/arena_enemy_namespace.inc.h"\n' + "\n".join(assets) + "\n" + cleanup,
        "arena_enemy_geo.inc.c": banner + '#include "levels/bowser_3/arena_enemy_assets.h"\n#include "levels/bowser_3/arena_enemy_namespace.inc.h"\n' + "\n".join(geos) + "\n" + cleanup,
    }

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in outputs().items():
        path = OUT / name
        if args.check:
            if not path.exists() or read_source(path) != content:
                raise SystemExit(f"Stale arena assets: {path}")
        else:
            path.write_text(content)
