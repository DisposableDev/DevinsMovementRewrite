#!/usr/bin/env python3
"""Generate the measured castle-painting and Goomba vertex groups."""

import argparse
from pathlib import Path
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "actors/goomba/model.inc.c"
PAINTING_MAPS = ROOT / "levels/castle_inside/painting.inc.c"
PAINTING_GROUPS = ROOT / "src/game/painting_vertex_groups.inc.c"
SUPPORTED = "defined(F3DEX_GBI_2) || defined(F3DEX_GBI) || defined(F3DLP_GBI)"
BEGIN = "// BEGIN GENERATED GOOMBA VERTEX GROUPS\n"
END = "// END GENERATED GOOMBA VERTEX GROUPS\n"


def numbers(text):
    return [int(value, 0) for value in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", text)]


def group_triangles(triangles):
    groups = []
    vertices, local = [], []
    for triangle in triangles:
        if len(set(vertices + list(triangle))) > 32 or len(local) == 64:
            groups.append((vertices, local))
            vertices, local = [], []
        remapped = []
        for vertex in triangle:
            if vertex not in vertices:
                vertices.append(vertex)
            remapped.append(vertices.index(vertex))
        local.append(remapped)
    if local:
        groups.append((vertices, local))
    assert [tuple(vertices[index] for index in triangle)
            for vertices, local in groups for triangle in local] == list(triangles)
    return groups


def painting_groups():
    output = ["// Generated by tools/generate_vertex_groups.py; triangle order is preserved.\n"]
    entries = []
    pattern = r"static const PaintingData (inside_castle_seg7_painting_texture_map_\w+)\[\] = \{(.*?)\};"
    for name, body in re.findall(pattern, read_source(PAINTING_MAPS), re.S):
        values = numbers(re.sub(r"//[^\n]*", "", body))
        count = values[0]
        triangle_count = values[count * 3 + 1]
        indices = values[count * 3 + 2:]
        assert 0 < count <= 255 and len(indices) == triangle_count * 3
        assert all(0 <= index < count for index in indices)
        groups = group_triangles([tuple(indices[i:i + 3]) for i in range(0, len(indices), 3)])
        symbol = "sCastlePaintingGroups" + str(len(entries))
        output.append("static const struct PaintingVertexGroup " + symbol + "[] = {\n")
        for vertices, local in groups:
            output.append("    {\n        " + str(len(vertices)) + ", " + str(len(local)) + ",\n")
            output.append("        { " + ", ".join(map(str, vertices)) + " },\n        {\n")
            for index in range(0, len(local), 8):
                output.append("            " + ", ".join(str(v) for tri in local[index:index + 8]
                                                        for v in tri) + ",\n")
            output.append("        },\n    },\n")
        output.append("};\n\n")
        vertex_count = sum(len(vertices) for vertices, _ in groups)
        commands = 6 + sum(1 + (len(local) + 1) // 2 for _, local in groups)
        entries.append((symbol, count, triangle_count, len(groups), vertex_count, commands))
    assert len(entries) == 2
    output.append("static const struct PaintingVertexGroups sCastlePaintingVertexGroups[] = {\n")
    for symbol, *counts in entries:
        output.append("    { " + symbol + ", " + ", ".join(map(str, counts)) + " },\n")
    output.append("};\n")
    return "".join(output)


def goomba_groups():
    source = read_source(MODEL)
    if BEGIN in source:
        start = source.index(BEGIN)
        end = source.index(END, start) + len(END)
        source = source[:start] + source[end:]
        pattern = r"#if " + re.escape(SUPPORTED) + r"\n.*?#else\n(.*?)#endif\n"
        source = re.sub(pattern, lambda match: match[1].rstrip("\n"), source, flags=re.S)
    arrays = {}
    for name, body in re.findall(r"static const Vtx (\w+)\[\] = \{(.*?)\n\};", source, re.S):
        rows = [tuple(numbers(row)) for row in body.splitlines() if numbers(row)]
        assert all(len(row) == 10 for row in rows), name
        arrays[name] = rows
    generated = []

    def repack(match):
        tokens = re.findall(r"(gsSP\w+)\(([^)]*)\)", match[0])
        if tokens[0][0] != "gsSPVertex":
            return match[0]
        triangles = []
        cache = None
        for operation, arguments in tokens:
            args = [arg.strip() for arg in arguments.split(",")]
            if operation == "gsSPVertex":
                assert args[0] in arrays and int(args[2], 0) == 0
                cache = arrays[args[0]][:int(args[1], 0)]
            else:
                values = [int(arg, 0) for arg in args]
                for offset in range(0, len(values), 4):
                    assert values[offset + 3] == 0
                    triangles.append(tuple(cache[index] for index in values[offset:offset + 3]))
        commands = []
        for vertices, local in group_triangles(triangles):
            symbol = "sGoombaVertexGroup" + str(len(generated))
            data = ["ALIGNED16 static const Vtx " + symbol + "[] = {\n"]
            for x, y, z, flag, u, v, r, g, b, a in vertices:
                data.append("    {{{%6d, %6d, %6d}, %d, {%6d, %6d}, "
                            "{0x%02x, 0x%02x, 0x%02x, 0x%02x}}},\n"
                            % (x, y, z, flag, u, v, r, g, b, a))
            data.append("};\n")
            generated.append("".join(data))
            commands.append("    gsSPVertex(%s, %d, 0),\n" % (symbol, len(vertices)))
            for index in range(0, len(local), 2):
                if index + 1 < len(local):
                    commands.append("    gsSP2Triangles(%d, %d, %d, 0, %d, %d, %d, 0),\n"
                                    % tuple(local[index] + local[index + 1]))
                else:
                    commands.append("    gsSP1Triangle(%d, %d, %d, 0),\n" % tuple(local[index]))
        # Keep the original commands as the source for regeneration and for older microcodes.
        original = match[0].lstrip("\n")
        return ("\n#if " + SUPPORTED + "\n" + "".join(commands) + "#else\n"
                + original + "\n#endif\n")

    blocks = r"(?:\s*gsSP(?:Vertex|1Triangle|2Triangles)\([^)]*\),)+"
    packed = re.sub(blocks, repack, source)
    # Original tables remain the regeneration source and serve the legacy microcode fallback.
    packed = re.sub(r"(?<!UNUSED )\bstatic const Vtx ", "UNUSED static const Vtx ", packed)
    return BEGIN + "#if " + SUPPORTED + "\n" + "\n".join(generated) + "#endif\n" + END + packed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated assets without changing them")
    args = parser.parse_args()
    outputs = {MODEL: goomba_groups(), PAINTING_GROUPS: painting_groups()}
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or read_source(path) != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        parser.exit(1, "Stale vertex groups: " + ", ".join(stale) + "\n")
    print("Vertex groups checked" if args.check else "Vertex groups generated")


if __name__ == "__main__":
    main()
