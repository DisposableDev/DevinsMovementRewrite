#!/usr/bin/env python3
"""Copy native guest meshes into the castle segment with private names and fade materials."""
from pathlib import Path
import argparse
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'levels/castle_inside/areas/4'
ACTORS = ('peach', 'bobomb', 'koopa', 'bowser', 'piranha_plant', 'motos')
BANNER = '// Generated by tools/generate_castle_lobby_guests.py from native actor assets.\n'
ANIMATIONS = {
    'peach': 'peach_seg5_anims_0501C41C',
    'bobomb': 'bobomb_seg8_anims_0802396C',
    'koopa': 'koopa_seg6_anims_06011364',
    'bowser': 'bowser_seg6_anims_06057690',
    'piranha_plant': 'piranha_plant_seg6_anims_0601C31C',
    'motos': 'motos_anime',
}


def expand_animation(path):
    text = read_source(path)
    return re.sub(r'^#include "([^"\n]+\.inc\.c)"$',
                  lambda m: expand_animation(path.parent / m[1]), text, flags=re.M)


def local_identifier(name, actor):
    return (name.startswith(actor + '_') or (actor == 'motos' and 'motos' in name)
            or (actor == 'bobomb' and name == 'black_bobomb_geo'))


def renamed(text, actor):
    # Quoted texture include paths still refer to the original texture assets.
    return re.sub(r'"(?:\\.|[^"\\])*"|\b[A-Za-z_]\w*\b',
                  lambda m: 'castle_lobby_' + m[0] if local_identifier(m[0], actor) else m[0], text)


def fade_materials(text):
    modes = {'G_CC_SHADE': 'G_CC_SHADEFADEA',
             'G_CC_MODULATERGB': 'G_CC_MODULATERGBFADEA',
             'G_CC_MODULATERGBA': 'G_CC_MODULATERGBFADEA',
             'G_CC_DECALRGBA': 'G_CC_DECALFADEA'}
    for old, new in modes.items():
        text = re.sub(r'\b' + old + r'\b', new, text)
    # Each guest's geometry callback owns its environment alpha.
    text = re.sub(r'^\s*gsDPSetEnvColor\([^\n]*\),\n', '\n', text, flags=re.M)
    return text


def opacity_layouts(layout):
    """Keep native depth-writing meshes at full opacity; select fade copies during arrival."""
    layout = re.sub(r'^\s*GEO_ASM\([^\n]*geo_update_layer_transparency\),\n', '\n', layout, flags=re.M)
    layout = re.sub(r'^UNUSED static const u64[^\n]*\n', '', layout, flags=re.M)
    names = set(re.findall(r'const GeoLayout (\w+)\[\]', layout))
    roots = re.findall(r'const GeoLayout (\w+)\[\] = \{(?:(?!const GeoLayout).)*?GEO_END\(\)',
                       layout, flags=re.S)
    outputs = []
    for fading in (False, True):
        suffix = '_fade' if fading else '_opaque'
        variant = re.sub(r'\b[A-Za-z_]\w*\b',
                         lambda m: m[0] + suffix if m[0] in names else m[0], layout)
        if fading:
            variant = re.sub(r'\bLAYER_\w+\b', 'LAYER_TRANSPARENT', variant)
        layers = sorted(set(re.findall(r'\bLAYER_\w+\b', variant)))
        start = ''.join('\n    GEO_ASM(' + layer + ', geo_castle_lobby_guest_alpha),'
                        for layer in layers)
        finish = ''.join('GEO_ASM(0x100 | ' + layer + ', geo_castle_lobby_guest_alpha),\n   '
                         for layer in layers)
        for root in roots:
            variant = re.sub(r'(const GeoLayout ' + root + suffix +
                             r'\[\] = \{.*?GEO_OPEN_NODE\(\),)',
                             lambda m: m[1] + start, variant, count=1, flags=re.S)
        variant = variant.replace('GEO_END(),', finish + 'GEO_RETURN(),')
        outputs.append(variant)
    for root in roots:
        outputs.append('const GeoLayout ' + root + '[] = {\n'
                       '    GEO_SWITCH_CASE(2, geo_switch_castle_lobby_guest_opacity),\n'
                       '    GEO_OPEN_NODE(),\n'
                       '    GEO_NODE_START(),\n'
                       '    GEO_OPEN_NODE(),\n'
                       '    GEO_BRANCH(1, ' + root + '_opaque),\n'
                       '    GEO_CLOSE_NODE(),\n'
                       '    GEO_NODE_START(),\n'
                       '    GEO_OPEN_NODE(),\n'
                       '    GEO_BRANCH(1, ' + root + '_fade),\n'
                       '    GEO_CLOSE_NODE(),\n'
                       '    GEO_CLOSE_NODE(),\n'
                       '    GEO_END(),\n};\n')
    return '\n'.join(outputs)


def generate():
    model, geo, declarations = [BANNER], [BANNER], [BANNER]
    for actor in ACTORS:
        folder = ROOT / 'actors' / actor
        mesh = renamed(read_source(folder / 'model.inc.c'), actor)
        model.append(fade_materials(mesh))
        if actor == 'motos':
            animation = read_source(folder / 'anims/anim.inc.c')
        else:
            animation = expand_animation(folder / 'anims/data.inc.c')
            animation += expand_animation(folder / 'anims/table.inc.c')
        model.append(renamed(animation, actor))
        layout = renamed(read_source(folder / 'geo.inc.c'), actor)
        layout = opacity_layouts(layout)
        geo.append(layout)
        identifiers = set(re.findall(r'\bcastle_lobby_\w+\b', layout))
        geo_names = set(re.findall(r'const GeoLayout (\w+)\[\]', layout))
        for name in sorted(identifiers):
            if name == "castle_lobby_guest_alpha" or "_unused_" in name:
                continue
            kind = 'GeoLayout' if name in geo_names else 'Gfx'
            declarations.append(f'extern const {kind} {name}[];\n')
        declarations.append('extern const struct Animation *const castle_lobby_'
                            + ANIMATIONS[actor] + '[];\n')
    # MIPS uses the already-loaded castle actor bin; only his geo needs a local alpha callback.
    mips = read_source(ROOT / 'actors/mips/geo.inc.c').replace('const GeoLayout mips_geo[]',
                                                            'const GeoLayout castle_lobby_mips_geo[]')
    mips = opacity_layouts(mips)
    geo.append(mips)
    declarations.append('extern const GeoLayout castle_lobby_mips_geo[];\n')
    return {'guest_models.inc.c': '\n'.join(model), 'guest_geos.inc.c': '\n'.join(geo),
            'guest_assets.h': '\n'.join(declarations)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generate().items():
        path = OUT / name
        if args.check:
            if not path.exists() or read_source(path) != text:
                raise SystemExit('Stale guest asset: ' + str(path))
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
