#!/usr/bin/env python3
"""Generate ordered, 32-vertex JRB ship LODs from the detailed native mesh."""
from pathlib import Path
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "levels/jrb/wooden_ship/model.inc.c"
OUTPUT = ROOT / "levels/jrb/wooden_ship/far_model.inc.c"
VARIANTS = (("medium", 128), ("far", 256), ("very_far", 512))
PARTS = ("07008FD8", "070090B0", "07009A58", "07009B30", "0700A608", "0700AC68")


def generate():
    arrays = {name: (kind, body) for kind, name, body in re.findall(
        r"\b(Vtx|Gfx)\s+(\w+)\[\]\s*=\s*\{(.*?)\n\};", read_source(SOURCE), re.S)}
    vertices = {}
    for name, (kind, body) in arrays.items():
        if kind == "Vtx":
            rows = re.findall(r"\{\{\{.*?\}\}\}", re.sub(r"\s+", "", body))
            vertices[name] = [tuple(int(value, 0) for value in
                                    re.findall(r"0x[\da-fA-F]+|-?\d+", row)) for row in rows]
    output = ["// Generated by tools/generate_jrb_ship_lods.py.\n"
              "// Native UVs, normals, materials and triangle order are retained.\n"]
    for variant, grid in VARIANTS:
        for part in PARTS:
            name = f"jrb_ship_{variant}_dl_{part}"
            cache = {}
            batch = []
            triangles = []
            commands = []
            batch_number = 0

            def flush():
                nonlocal batch_number
                if not triangles:
                    return
                vertex_name = f"jrb_ship_{variant}_vertex_{part}_{batch_number}"
                batch_number += 1
                output.append(f"static const Vtx {vertex_name}[] = {{\n")
                for x, y, z, flag, u, v, r, g, b, a in batch:
                    output.append(f"    {{{{{{{x}, {y}, {z}}}, {flag}, {{{u}, {v}}}, "
                                  f"{{0x{r:02x}, 0x{g:02x}, 0x{b:02x}, 0x{a:02x}}}}}}},\n")
                output.append("};\n\n")
                commands.append(f"    gsSPVertex({vertex_name}, {len(batch)}, 0),\n")
                for offset in range(0, len(triangles), 2):
                    pair = triangles[offset:offset + 2]
                    operation = "gsSP2Triangles" if len(pair) == 2 else "gsSP1Triangle"
                    fields = ", ".join(str(value) for triangle in pair for value in triangle)
                    commands.append(f"    {operation}({fields}),\n")
                batch.clear()
                triangles.clear()

            def visit(display):
                for operation, arguments in re.findall(r"(gs\w+)\((.*?)\),", arrays[display][1], re.S):
                    fields = [field.strip() for field in arguments.split(",")]
                    if operation == "gsSPDisplayList":
                        visit(fields[0])
                    elif operation == "gsSPVertex":
                        count, start = int(fields[1]), int(fields[2])
                        if count + start > 32 or count > len(vertices[fields[0]]):
                            raise ValueError("Invalid native vertex load")
                        for index, vertex in enumerate(vertices[fields[0]][:count]):
                            position = tuple(round(value / grid) * grid for value in vertex[:3])
                            cache[start + index] = position + vertex[3:]
                    elif operation in ("gsSP1Triangle", "gsSP2Triangles"):
                        for offset in range(0, len(fields), 4):
                            triangle = tuple(cache[int(field)] for field in fields[offset:offset + 3])
                            if len({vertex[:3] for vertex in triangle}) < 3:
                                continue
                            if len(set(batch) | set(triangle)) > 32:
                                flush()
                            indices = []
                            for vertex in triangle:
                                if vertex not in batch:
                                    batch.append(vertex)
                                indices.append(batch.index(vertex))
                            triangles.append(tuple(indices) + (int(fields[offset + 3], 0),))
                    elif operation != "gsSPEndDisplayList":
                        flush()
                        commands.append(f"    {operation}({', '.join(fields)}),\n")

            visit("jrb_seg7_dl_" + part)
            flush()
            output.append(f"const Gfx {name}[] = {{\n")
            output.extend(commands)
            output.append("    gsSPEndDisplayList(),\n};\n\n")
    return "".join(output)


if __name__ == "__main__":
    OUTPUT.write_text(generate())
