#!/usr/bin/env python3
"""Give the lab a private enemy asset bank, leaving the stock banks untouched.

All generated includes reuse the original meshes/animations. Behavior identities
are preserved, including child spawns, so the game's custom enemy interactions
continue to see the real behaviors. Run with --check to verify generated files.
"""
import argparse
from pathlib import Path
import re

try:
    from .source_asset import read_text as read_source
except ImportError:
    from source_asset import read_text as read_source

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "levels/physics_lab"
ACTORS = """thwomp bullet_bill heave_ho bully clam_shell sushi unagi klepto pokey
tornado monty_mole_hole monty_mole fwoosh spindrift snowman bookend book chair
mad_piano boo lakitu_enemy spiny_egg spiny bubba bub skeeter koopa piranha_plant
whomp chain_ball chain_chomp poundable_pole chillychief moneybag mr_i_eyeball
mr_i_iris swoop snufit scuttlebug ukiki water_bubble treasure_chest""".split()
# A model's original numeric slot is not unique across banks. Pair it with the
# owning behavior, including every child and model-changing behavior.
OWNERS = {
    "THWOMP": "Thwomp", "BULLET_BILL": "BulletBill", "HEAVE_HO": "HeaveHo",
    "BULLY": "SmallBully", "CLAM_SHELL": "ClamShell", "SUSHI": "SushiShark",
    "UNAGI": "Unagi", "KLEPTO": "Klepto", "POKEY_HEAD": "PokeyBodyPart",
    "POKEY_BODY_PART": "PokeyBodyPart", "TWEESTER": "Tweester",
    "DL_MONTY_MOLE_HOLE": "MontyMoleHole", "MONTY_MOLE": "MontyMole",
    "FWOOSH": "CloudPart", "SPINDRIFT": "Spindrift",
    "MR_BLIZZARD_HIDDEN": "MrBlizzard", "MR_BLIZZARD": "MrBlizzard",
    "BOOKEND_PART": "FlyingBookend", "BOOKEND": "FlyingBookend",
    "HAUNTED_CHAIR": "HauntedChair", "MAD_PIANO": "MadPiano", "BOO": "Boo",
    "ENEMY_LAKITU": "EnemyLakitu", "SPINY_BALL": "Spiny", "SPINY": "Spiny",
    "BUBBA": "Bubba", "BUB": "Bub", "SKEETER": "Skeeter",
    "KOOPA_WITH_SHELL": "Koopa", "KOOPA_WITHOUT_SHELL": "Koopa",
    "PIRANHA_PLANT": "PiranhaPlant FirePiranhaPlant", "WHOMP": "SmallWhomp",
    "METALLIC_BALL": "ChainChompChainPart", "CHAIN_CHOMP": "ChainChomp",
    "WOODEN_POST": "WoodenPost", "CHILL_BULLY": "SmallChillBully",
    "MONEYBAG": "Moneybag MoneybagHidden", "MR_I_BODY": "MrI", "MR_I_IRIS": "MrIIris",
    "SWOOP": "Swoop", "SNUFIT": "Snufit", "SCUTTLEBUG": "Scuttlebug", "UKIKI": "Ukiki",
    "SSL_GRINDEL": "Grindel HorizontalGrindel", "SSL_SPINDEL": "Spindel", "SSL_TOX_BOX": "ToxBox",
    "WATER_BOMB": "WaterBomb", "WATER_BOMB_SHADOW": "WaterBombShadow",
    "HMC_ROLLING_ROCK": "BigBoulder",
    "TREASURE_CHEST_BASE": "TreasureChestBottom", "TREASURE_CHEST_LID": "TreasureChestTop",
}
DEFINITION = re.compile(
    r"^(?P<qual>(?:(?:UNUSED|ALIGNED8|static|const)\s+)*)"
    r"(?P<type>struct Animation|Lights[0-9]|Vtx|Gfx|GeoLayout|Collision|Trajectory|s16|u16|u8|u64|Texture)"
    r"\s+(?P<ptr>(?:\*\s*(?:const\s*)?)?)(?P<name>\w+)\s*"
    r"(?P<array>\[[^\]]*\])?\s*=", re.M)


def outputs():
    dirs = [ROOT / "actors" / name for name in ACTORS]
    dirs += [ROOT / "levels/ssl" / name for name in ("grindel", "spindel", "tox_box")]
    dirs += [ROOT / "levels/hmc/rolling_rock"]
    defs = {}
    for directory in dirs:
        for path in sorted(directory.rglob("*.inc.c")):
            for match in DEFINITION.finditer(read_source(path)):
                name = match["name"]
                assert name not in defs, (name, path)
                defs[name] = match.groupdict()
    # Grindel and Spindel share two SSL textures outside their model includes.
    textures = []
    for level,name in (("ssl","ssl_seg7_texture_07002800"),("ssl","ssl_seg7_texture_07003800"),
                       ("hmc","hmc_seg7_texture_07004800")):
        texture_text = read_source(ROOT / f"levels/{level}/texture.inc.c")
        block = re.search(r"ALIGNED8 static const Texture " + name + r"\[\] = \{.*?\};", texture_text, re.S)
        assert block, name
        textures.append(block[0])
        defs[name] = DEFINITION.search(block[0]).groupdict()

    banner = "// Generated by tools/generate_physics_lab_enemies.py; edit the generator.\n"
    rename = lambda name: "physics_lab_enemy_" + name
    namespace = banner + "\n".join(f"#define {name} {rename(name)}" for name in sorted(defs)) + "\n"
    cleanup = "\n".join(f"#undef {name}" for name in sorted(defs)) + "\n"
    declarations = []
    original_declarations = []
    for name,d in sorted(defs.items()):
        if "static" in d["qual"]:
            continue
        suffix = "[]" if d["array"] else ""
        declaration = f"extern const {d['type']} {d['ptr']}{name}{suffix};"
        if d['type'] == "Collision" or d['type'] == "struct Animation":
            original_declarations.append(declaration)
        declarations.append(declaration.replace(name, rename(name)))

    assets = [banner, '#include "levels/physics_lab/enemy_namespace.inc.h"', *textures]
    geos = [banner, '#include "levels/physics_lab/enemy_assets.h"',
            '#include "levels/physics_lab/enemy_namespace.inc.h"']
    for directory in dirs:
        for filename in ("model.inc.c", "anims/data.inc.c", "anims/table.inc.c", "collision.inc.c"):
            path = directory / filename
            if path.exists():
                assets.append(f'#include "{path.relative_to(ROOT)}"')
        path = directory / "geo.inc.c"
        if path.exists():
            geos.append(f'#include "{path.relative_to(ROOT)}"')
    assets.append(cleanup)
    geos.append(cleanup)

    scripts = "\n".join(read_source(ROOT / path) for path in
                        ("levels/scripts.c", "levels/ssl/script.c", "levels/hmc/script.c"))
    models = {}
    for model,geo in re.findall(r"LOAD_MODEL_FROM_GEO\(\s*MODEL_(\w+),\s*(\w+)\)", scripts):
        if model in OWNERS:
            assert geo in defs, geo
            models[model] = (geo, None)
    models["DL_MONTY_MOLE_HOLE"] = ("monty_mole_hole_seg5_dl_05000840", "LAYER_TRANSPARENT_DECAL")
    assert models.keys() == OWNERS.keys(), (OWNERS.keys() - models.keys())
    ids = {name: 0x20+i for i,name in enumerate(OWNERS)}
    assert max(ids.values()) < 0x74  # Common actors start at 0x74.
    enum = "enum PhysicsLabEnemyModel {\n" + "\n".join(f"    LAB_MODEL_{name} = 0x{value:02X}," for name,value in ids.items()) + "\n};\n"
    loads = [banner]
    for name,(geo,layer) in models.items():
        if layer:
            loads.append(f"LOAD_MODEL_FROM_DL(LAB_MODEL_{name}, {rename(geo)}, {layer}),")
        else:
            loads.append(f"LOAD_MODEL_FROM_GEO(LAB_MODEL_{name}, {rename(geo)}),")

    # Match each original script to the assets it loads. Shared GOTO scripts
    # retain the child's behavior identity, so explicitly include those users.
    behavior_text = read_source(ROOT / "data/behavior_data.c")
    bodies = dict(re.findall(r"const BehaviorScript (\w+)\[\] = \{(.*?)\n\};", behavior_text, re.S))
    mappings = set()
    def collect(behavior, body, seen):
        for asset in re.findall(r"LOAD_ANIMATIONS\(\w+,\s*(\w+)\)|LOAD_COLLISION_DATA\((\w+)\)", body):
            name = next(x for x in asset if x)
            if name in defs:
                mappings.add((behavior, name))
        for other in re.findall(r"(?:GOTO|CALL)\((bhv\w+)", body):
            if other not in seen and other in bodies:
                collect(behavior, bodies[other], seen | {other})
    owners = {"bhv" + owner for names in OWNERS.values() for owner in names.split()}
    for behavior in sorted(owners):
        collect(behavior, bodies[behavior], {behavior})
    for asset in ("spiny_egg_seg5_anims_050157E4", "spiny_seg5_anims_05016EAC"):
        mappings.add(("bhvSpiny", asset))
    table = [banner, *original_declarations,
             "static const struct LabAssetRemap sLabAssets[] = {"]
    table += [f"    {{ {behavior}, {asset}, {rename(asset)} }}," for behavior,asset in sorted(mappings)]
    table += ["};", "static const struct LabModelRemap sLabModels[] = {"]
    for model,owners in OWNERS.items():
        for owner in owners.split():
            assert "bhv" + owner in bodies, owner
            table.append(f"    {{ bhv{owner}, MODEL_{model}, LAB_MODEL_{model} }},")
    table += ["};"]
    return {
        "enemy_namespace.inc.h": namespace,
        "enemy_assets.h": banner + "#ifndef PHYSICS_LAB_ENEMY_ASSETS_H\n#define PHYSICS_LAB_ENEMY_ASSETS_H\n#include \"types.h\"\n" + "\n".join(declarations) + "\n" + enum + "#endif\n",
        "enemy_assets.inc.c": "\n".join(assets) + "\n",
        "enemy_geo.inc.c": "\n".join(geos) + "\n",
        "enemy_models.inc.c": "\n".join(loads) + "\n",
        "enemy_remap.inc.c": "\n".join(table) + "\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name,text in outputs().items():
        path = OUT / name
        if args.check:
            if not path.exists() or read_source(path) != text:
                raise SystemExit(f"Stale enemy assets: {path}")
        else:
            path.write_text(text)
    print("Physics Lab enemy bank: " + ("verified" if args.check else "generated"))
